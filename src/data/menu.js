export const dishes = menuRows.map(
    ([categoryId, id, name, price, weight = null, description = null]) => ({
        id,
        categoryId,
        name,
        price,
        weight,
        description: compositionOverrides.get(id) ?? description,
        image: imageOverrides.get(id) ??
            `/images/menu/${id}.${suppliedPhotoIds.has(id) ? 'jpg' : 'webp'}`,
    })
);

export function getDishById(id) {
    return dishes.find((dish) => dish.id === id) || null;
}

export function getDishesByCategory(categoryId) {
    return dishes.filter((dish) => dish.categoryId === categoryId);
}
